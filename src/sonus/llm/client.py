"""
Asynchronous streaming LLM client communicating with Ollama with deterministic sentence chunking.

Pipelining Rationale:
    Waiting for the LLM to complete generating a full paragraph before synthesizing
    speech introduces unacceptable latency (1.5s - 3.5s). By extracting completed
    sentences in real time as tokens arrive over the HTTP stream, the TTS synthesizer
    can generate and enqueue the opening sentence while subsequent sentences are still
    being generated by the model.
"""

import json
import re
from typing import AsyncGenerator, List, Optional, Tuple
import httpx

from sonus.config import LLMConfig


class StreamingLLMClient:
    """
    Async streaming client executing local LLM inference with sentence-boundary chunking.
    
    Lexical Boundary Protection:
        The regex automata guards against premature sentence fragmentation caused by:
        - Professional honorifics and titles (Dr., Mr., Prof., Sen., Capt.)
        - Latin abbreviations and explanatory terms (e.g., i.e., etc., al.)
        - Dotted uppercase acronyms (U.S., U.K., C.I.A.)
        - Floating-point decimals and currency markers ($3.14, 0.05)
        - Enumeration list indices (1., 2.)
    """

    TITLES = {
        "dr", "mr", "mrs", "ms", "prof", "sr", "jr", "rev", "gen", "rep",
        "sen", "gov", "capt", "col", "maj", "sgt", "st", "rd", "ave", "blvd",
        "dept", "approx", "est", "min", "sec", "no", "nos", "vs", "vol", "vols",
        "ch", "fig"
    }
    EXPLANATORY = {"e.g", "eg", "i.e", "ie", "vs", "viz", "etc", "al"}

    _BOUNDARY_PATTERN = re.compile(r'([.?!]+[\"\'\)\]\}]*)(\s+)')

    def __init__(self, config: LLMConfig):
        self.config = config

    @staticmethod
    def _is_capitalized_acronym(raw_word: str) -> bool:
        """Evaluate whether a token represents an uppercase dotted acronym."""
        clean = raw_word.strip("()[]\"\'$,")
        parts = clean.rstrip(".").split(".")
        return len(parts) >= 2 and all(len(p) == 1 and p.isupper() for p in parts)

    def extract_sentences(self, buffer: str, is_final: bool = False) -> Tuple[List[str], str]:
        """
        Scan incoming streaming token buffer and partition out syntactically complete sentences.
        
        Args:
            buffer: Cumulative accumulated string of incoming LLM tokens.
            is_final: If True, flushes trailing buffered text regardless of terminal punctuation.
            
        Returns:
            Tuple[List[str], str]: (completed_sentences, remaining_uncompleted_buffer)
        """
        sentences: List[str] = []
        pos = 0

        while True:
            match = self._BOUNDARY_PATTERN.search(buffer[pos:])
            if not match:
                break

            punct = match.group(1)
            match_start = pos + match.start(1)
            punct_end = match_start + len(punct)
            after_space = pos + match.end()
            next_char = buffer[after_space:after_space + 1]

            # Ambiguity resolution for periods
            if "." in punct:
                preceding = buffer[:match_start].strip()
                last_word = preceding.split()[-1] if preceding.split() else ""
                clean_word = last_word.lower().strip("()[]\"\'$,")

                if (
                    clean_word in self.TITLES
                    or (len(clean_word) == 1 and clean_word.isalpha())
                    or clean_word in self.EXPLANATORY
                    or self._is_capitalized_acronym(last_word)
                    or clean_word.isdigit()
                    or (next_char and (next_char.islower() or next_char.isdigit()))
                ):
                    pos = punct_end
                    continue

            sentence = buffer[:punct_end].strip()
            if sentence:
                sentences.append(sentence)
            buffer = buffer[after_space:]
            pos = 0

        if is_final:
            remaining = buffer.strip()
            if remaining:
                sentences.append(remaining)
                buffer = ""

        return sentences, buffer

    @staticmethod
    def sanitize_spoken_text(text: str) -> str:
        """Strip roleplay actions, markdown asterisks, headers, and bracketed notes."""
        # Strip asterisks used for roleplay actions, e.g. *chuckles*, *sighs*
        cleaned = re.sub(r'\*[^*]*\*', '', text)
        # Strip square bracketed stage directions, e.g. [interrupted], [laughter]
        cleaned = re.sub(r'\[[^\]]*\]', '', cleaned)
        # Strip markdown headers or symbols
        cleaned = cleaned.replace("*", "").replace("#", "").strip()
        return cleaned

    def get_system_prompt(self) -> str:
        """
        Dynamically format system prompt with live clock, calendar, and optional user context.
        """
        from datetime import datetime
        now = datetime.now()
        date_str = now.strftime("%A, %B %d, %Y")
        time_str = now.strftime("%I:%M %p")
        user_name = getattr(self.config, "user_name", None)
        base = self.config.system_prompt

        prompt = base.replace("{current_date}", date_str)\
                     .replace("{current_time}", time_str)\
                     .replace("{current_year}", str(now.year))

        if user_name:
            prompt = prompt.replace("{user_name}", user_name)
            if user_name not in prompt:
                prompt += (
                    f"\nContext: You are speaking with {user_name}. "
                    f"If asked about their identity or name, confirm their name is {user_name}."
                )
        else:
            prompt = prompt.replace("{user_name}", "the user")

        return prompt.strip()

    async def generate_sentences(
        self,
        user_message: str,
        conversation_history: Optional[List[dict]] = None
    ) -> AsyncGenerator[str, None]:
        """
        Stream LLM response chunked at natural sentence boundaries.
        
        Yields:
            Individual sentences as soon as they are fully completed.
        """
        messages = [{"role": "system", "content": self.get_system_prompt()}]
        if conversation_history:
            messages.extend(conversation_history)
        messages.append({"role": "user", "content": user_message})

        payload = {
            "model": self.config.model,
            "messages": messages,
            "stream": True,
            "options": {
                "temperature": self.config.temperature,
            }
        }

        url = f"{self.config.base_url.rstrip('/')}/api/chat"
        buffer = ""

        async with httpx.AsyncClient(timeout=30.0) as client:
            async with client.stream("POST", url, json=payload) as response:
                response.raise_for_status()

                async for line in response.aiter_lines():
                    if not line:
                        continue

                    try:
                        chunk = json.loads(line)
                    except json.JSONDecodeError:
                        continue

                    content = chunk.get("message", {}).get("content", "")
                    if content:
                        buffer += content
                        completed, buffer = self.extract_sentences(buffer, is_final=False)
                        for sent in completed:
                            cleaned = self.sanitize_spoken_text(sent)
                            if cleaned:
                                yield cleaned

                    if chunk.get("done", False):
                        break

        # Flush any trailing words that didn't end in punctuation
        final_sentences, _ = self.extract_sentences(buffer, is_final=True)
        for sent in final_sentences:
            cleaned = self.sanitize_spoken_text(sent)
            if cleaned:
                yield cleaned
